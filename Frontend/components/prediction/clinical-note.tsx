'use client'

import { useState } from 'react'
import { Check, ChevronDown, Copy, FileText } from 'lucide-react'
import { toast } from 'sonner'
import { Button } from '@/components/ui/button'
import { Panel } from '@/components/shared/panel'
import { cn } from '@/lib/utils'
import type { PredictionSource } from '@/lib/types'

const COLLAPSE_AT = 420

export function ClinicalNotePanel({ note, source, className }: { note: string; source: PredictionSource; className?: string }) {
  const [expanded, setExpanded] = useState(false)
  const [copied, setCopied] = useState(false)
  const long = note.length > COLLAPSE_AT

  async function copy() {
    try {
      await navigator.clipboard.writeText(note)
      setCopied(true)
      toast.success('Clinical note copied')
      setTimeout(() => setCopied(false), 1800)
    } catch {
      toast.error('Clipboard is unavailable in this browser context')
    }
  }

  return (
    <Panel
      className={className}
      title={
        <span className="flex items-center gap-2">
          <FileText className="size-4 text-primary" aria-hidden="true" />
          Clinical note
        </span>
      }
      description={
        source === 'demo'
          ? 'Synthetic placeholder text generated locally for Demo Mode — not a backend output.'
          : 'Generated by the CareSense backend and returned in the clinical_note field.'
      }
      action={
        <Button variant="outline" size="sm" onClick={copy} className="print:hidden">
          {copied ? <Check /> : <Copy />}
          {copied ? 'Copied' : 'Copy note'}
        </Button>
      }
    >
      <div className="relative">
        <p
          className={cn(
            'font-mono text-[13px] leading-relaxed whitespace-pre-wrap text-foreground/90 text-pretty',
            long && !expanded && 'line-clamp-6 print:line-clamp-none',
          )}
        >
          {note || 'The backend returned an empty clinical note.'}
        </p>
        {long && (
          <Button
            variant="ghost"
            size="sm"
            onClick={() => setExpanded((e) => !e)}
            aria-expanded={expanded}
            className="mt-2 -ml-2 text-primary print:hidden"
          >
            <ChevronDown className={cn('transition-transform', expanded && 'rotate-180')} />
            {expanded ? 'Collapse note' : 'Expand full note'}
          </Button>
        )}
      </div>
    </Panel>
  )
}
